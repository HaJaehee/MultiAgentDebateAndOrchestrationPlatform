"""드래그하는 동안 서버와 핑퐁하지 않는 스플리터."""

from nicegui import ui


class QuietSplitter(ui.splitter):
    """`ui.splitter` 와 같지만, 서버가 받은 값을 브라우저로 **되돌려 보내지 않습니다.**

    NiceGUI 의 스플리터는 드래그하는 동안 50ms 마다 값을 서버로 보내고(throttle 0.05),
    `LOOPBACK = True` 라서 서버가 그 값을 다시 브라우저로 돌려보냅니다. 돌아온 값마다
    양쪽 창을 한 번 더 배치하므로, 발언 카드가 많이 쌓인 피드에서는 끄는 내내 화면이
    버벅였습니다.

    브라우저가 이미 그 위치로 움직여 놓았으니 되돌려 받을 이유가 없습니다. 서버는 여전히
    값을 받으므로 `splitter.value` 는 최신입니다. 서버에서 값을 **바꾸면** 그때는
    브라우저로 나갑니다 — 되돌림만 끄는 것입니다.
    """

    LOOPBACK = False
